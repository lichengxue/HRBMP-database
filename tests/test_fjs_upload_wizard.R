# Exercise real Shiny event handlers and worker processes against a local mock API.
args <- commandArgs(trailingOnly = TRUE)
stopifnot(length(args) == 7L, grepl("^http://127[.]0[.]0[.]1:[0-9]+$", args[[6]]))
repo <- normalizePath(args[[1]], winslash = "/", mustWork = TRUE)
.libPaths(c(file.path(repo, "tools/shiny-library"), .libPaths()))
Sys.setenv(FJS_REPO_ROOT = repo, FJS_WORK_ROOT = args[[2]])
key <- Sys.getenv("FJS_WIZARD_TEST_KEY")
stopifnot(identical(key, "sb_secret_synthetic_test_value"))
env <- new.env()
source(file.path(repo, "archive_app/app.R"), local = env)
original_hash <- unname(tools::md5sum(args[[4]]))
shiny::testServer(env$server, {
  session$setInputs(work_root = args[[2]], source_mode = "zip", source_dir = args[[3]],
    zip_group = "FJS_Example-1", expected_parts = 3, confidential_csv = "",
    dictionary = args[[5]], batch_name = "Wizard_test", supabase_url = args[[6]], upsert = FALSE)
  session$flushReact()
  wait_for_worker <- function() {
    for (i in seq_len(250L)) {
      session$elapse(350)
      Sys.sleep(.05)
      session$flushReact()
      if (!busy()) return(invisible(NULL))
    }
    stop("Wizard worker did not finish in time.")
  }
  session$setInputs(review_next = 1)
  stopifnot(state$step == "source", is.null(state$package))
  session$setInputs(sidebar_step = "publish")
  stopifnot(state$step == "source")
  session$setInputs(source_next = 1)
  wait_for_worker()
  stopifnot(state$step == "metadata", state$source$samples == 1, state$source$assets == 4)
  merged_root <- state$source$root
  session$setInputs(sidebar_step = "source")
  stopifnot(state$step == "source")
  session$setInputs(source_mode = "raw", source_dir = merged_root, source_next = 2)
  stopifnot(state$step == "metadata")
  session$setInputs(prepare_next = 1)
  stopifnot(state$step == "metadata", nzchar(state$error), is.null(state$package))
  session$setInputs(confidential_csv = args[[4]], prepare_next = 2)
  wait_for_worker()
  if (nzchar(state$error)) stop(state$error, "\n", state$log)
  stopifnot(state$step == "review", state$package$samples == 1, state$package$assets == 4,
    identical(state$package$fingerprint, state$dry_fingerprint))
  session$setInputs(review_next = 2)
  stopifnot(state$step == "review")
  session$setInputs(qc_reviewed = TRUE, review_next = 3)
  stopifnot(state$step == "publish")
  session$setInputs(secret = key, sidebar_step = "review")
  stopifnot(state$step == "review", is.null(state$pending), state$secret == "")
  session$setInputs(sidebar_step = "metadata")
  stopifnot(state$step == "metadata")
  session$setInputs(sidebar_step = "publish")
  stopifnot(state$step == "metadata")
  session$setInputs(prepare_next = 3)
  stopifnot(state$step == "review", !busy())
  session$setInputs(back_metadata = 2)
  session$setInputs(batch_name = "Wizard_corrected", prepare_next = 4)
  session$setInputs(sidebar_step = "source")
  stopifnot(state$step == "metadata", busy())
  wait_for_worker()
  stopifnot(state$step == "review", !nzchar(state$error),
    identical(state$package$fingerprint, state$dry_fingerprint),
    state$package$tables$fjs_import_batches$batch_name == "Wizard_corrected")
  # Excluded photos are informational: they do not block progression.
  state$package$exclusions <- data.frame(asset_id = "excluded-synthetic",
    original_file_name = "synthetic-unmatched.jpg", reason = "No matching survey taxon row")
  stopifnot(grepl("does not block", output$excluded_photos_note$html, fixed = TRUE))
  session$setInputs(review_next = 4)
  stopifnot(state$step == "publish")
  session$setInputs(secret = key, publish = 1)
  stopifnot(!is.null(state$pending), state$step == "publish", !busy())
  session$setInputs(confirm_publish = 1)
  wait_for_worker()
  if (nzchar(state$error)) stop(state$error, "\n", state$log)
  stopifnot(state$step == "done", state$secret == "")
  stopifnot(state$upload_progress$uploaded == 4L, state$upload_progress$total == 4L,
    state$upload_progress$failed == 0L, state$upload_progress$phase == "complete")
  stopifnot(grepl("4/4 files uploaded", output$run_progress$html, fixed = TRUE))
  stopifnot(grepl("Download upload report", output$done_summary$html, fixed = TRUE))
  stopifnot(length(list.files(file.path(state$package$root, "reports"), pattern = "[.]txt$")) == 1L)
  session$setInputs(sidebar_step = "publish")
  stopifnot(state$step == "done")
  record <- readRDS(file.path(args[[2]], "upload_progress.rds"))
  stopifnot(record$completed, !any(grepl(key, as.character(unlist(record)), fixed = TRUE)))
  restored <- fjs_wizard_resume(args[[2]], repo)
  stopifnot(restored$completed, restored$package$samples == 1)
  stopifnot(identical(unname(tools::md5sum(args[[4]])), original_hash))
})
resume_root <- paste0(args[[2]], "-resume")
dir.create(file.path(resume_root, "jobs"), recursive = TRUE)
merge_request <- list.files(file.path(args[[2]], "jobs"), pattern = "^merge-.*[.]rds$", full.names = TRUE)
merge_request <- merge_request[!grepl("[.]result[.]rds$", merge_request)]
stopifnot(length(merge_request) == 1L)
file.copy(merge_request, file.path(resume_root, "jobs", basename(merge_request)))
shiny::testServer(env$server, {
  session$setInputs(work_root = resume_root, source_mode = "zip", source_dir = args[[3]])
  session$flushReact()
  stopifnot(state$step == "metadata", state$source$samples == 1, state$source$assets == 4,
    is.null(state$process), is.null(state$package))
})
cat("Wizard: merge -> survey data -> prepare/check -> review -> upload/verify -> done passed.\n")

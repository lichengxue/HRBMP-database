repo <- normalizePath(commandArgs(trailingOnly = TRUE)[[1]], winslash = "/", mustWork = TRUE)
.libPaths(c(file.path(repo, "tools/shiny-library"), .libPaths()))
source(file.path(repo, "archive_app/workflow.R"))
source(file.path(repo, "scripts/bump_fjs_app_version.R"))
base <- list(uploaded = 0, failed = 0, total = 615, phase = "tables")
event <- 'FJS_UPLOAD_PROGRESS {"uploaded":30,"failed":2,"total":615}\n'
progress <- fjs_app_upload_progress(base, event)
stopifnot(progress$uploaded == 30, progress$failed == 2, progress$phase == "upload")
stopifnot(identical(progress, fjs_app_upload_progress(progress, 'FJS_UPLOAD_PROGRESS {"uploaded":31,"failed":2,"total":999}')))
stopifnot(identical(progress, fjs_app_upload_progress(progress, 'FJS_UPLOAD_PROGRESS {"uploaded":-1,"failed":2,"total":615}')))
stopifnot(identical(progress, fjs_app_upload_progress(progress, 'FJS_UPLOAD_PROGRESS not-json')))
stopifnot(fjs_app_upload_progress(progress, "Verifying saved database rows and Storage file sizes")$phase == "verify")
partial <- fjs_app_log_chunk("", "FJS_UPLOAD_PRO")
stopifnot(identical(partial$clean, ""))
rest <- fjs_app_log_chunk(partial$pending, 'GRESS {"uploaded":30,"failed":2,"total":615}\n')
stopifnot(fjs_app_upload_progress(base, rest$clean)$uploaded == 30)
temporary <- tempfile("fjs-version-")
dir.create(file.path(temporary, "archive_app"), recursive = TRUE)
writeLines("1.2.3", file.path(temporary, "archive_app/VERSION"))
jsonlite::write_json(list(list(version = "1.2.3", date = "2026-11-03", notes = list("Synthetic"))),
  file.path(temporary, "archive_app/releases.json"), auto_unbox = TRUE)
stopifnot(bump_fjs_app_version(temporary, "patch", "Synthetic fix") == "1.2.4")
stopifnot(bump_fjs_app_version(temporary, "minor", "Synthetic feature") == "1.3.0")
stopifnot(bump_fjs_app_version(temporary, "major", "Synthetic breaking change") == "2.0.0")
stopifnot(fjs_app_version(temporary) == "2.0.0")
before <- readLines(file.path(temporary, "archive_app/VERSION"))
stopifnot(inherits(try(bump_fjs_app_version(temporary, "patch", ""), silent = TRUE), "try-error"))
stopifnot(identical(before, readLines(file.path(temporary, "archive_app/VERSION"))))
stopifnot(identical(normalizePath(dirname(temporary)), normalizePath(tempdir())))
unlink(temporary, recursive = TRUE)
cat("Upload progress parsing, partial log lines, and patch/minor/major version updates verified.\n")
